type FormState = {
  configName: string;
  industry: Industry;
  assistantName: string;
  assistantPersona: string;
  targetLanguage: string;
  responseChannel: ResponseChannel;
  domainDescription: string;
  useCaseDescription: string;
  toneStyle: ToneStyle;
  defaultSentences: number;
  maxSentences: number;
  greetings: string;
  midAcks: string;
  problemHandling: ProblemHandlingMode;
  useBullets: boolean;
  preferSimple: boolean;
  avoidJargon: boolean;
  customInstructions: string;
  userPersona: string;
  requiredKeys: string;
  fallbackText: string;
  missingDataBehavior: MissingDataBehavior;
  preventHallucination: boolean;
  blockFinancial: boolean;
  requireGrounding: boolean;
  ragEnabled: boolean;
};

const INDUSTRIES: Industry[] = ["agriculture", "banking", "telecom", "healthcare", "education", "restaurant", "custom"];
const TONES: ToneStyle[] = ["casual-expert", "formal-secure", "empathetic-direct", "friendly-local", "professional-concise"];
const CHANNELS: ResponseChannel[] = ["voice", "text", "chat", "call-center"];
const PROBLEM_MODES: ProblemHandlingMode[] = ["diagnostic-probe", "direct-remediation", "escalation", "educational-explanation"];
const MISSING_DATA_MODES: MissingDataBehavior[] = ["ask-follow-up", "say-not-available", "escalate", "provide-general-guidance-only"];

function buildConfigFromForm(form: FormState): PromptConfiguration {
  return {
    meta: {
      configName: form.configName || "Custom Config",
      industry: form.industry,
      assistantName: form.assistantName || "Assistant",
      assistantPersona: form.assistantPersona,
      targetLanguage: form.targetLanguage || "English",
      responseChannel: form.responseChannel,
      domainDescription: form.domainDescription || "General assistant",
      useCaseDescription: form.useCaseDescription,
    },
    behavioralOptions: {
      toneStyle: form.toneStyle,
      lengthConstraint: {
        unit: "sentences",
        defaultValue: form.defaultSentences,
        maxElaborationValue: form.maxSentences,
        allowUserRequestedElaboration: true,
      },
      greetingPolicy: {
        initialGreetingsAllowed: form.greetings
          .split(",")
          .map((g) => g.trim())
          .filter(Boolean),
        midConversationAcks: form.midAcks
          .split(",")
          .map((m) => m.trim())
          .filter(Boolean),
        allowInitialGreetingOnlyOnce: true,
        allowRepetition: false,
        requireLocalRespectWords: false,
      },
      problemHandlingMode: form.problemHandling,
      answerStyle: {
        useBulletPoints: form.useBullets,
        useMarkdown: true,
        askFollowUpWhenNeeded: form.problemHandling === "diagnostic-probe",
        preferSimpleLanguage: form.preferSimple,
        avoidTechnicalJargon: form.avoidJargon,
      },
      personalization: {
        userPersona: form.userPersona,
        assistantPersona: form.assistantPersona,
      },
      customInstructionBlocks: form.customInstructions
        .split("\n")
        .map((line) => line.trim())
        .filter(Boolean),
    },
    dataMapping: {
      requiredStructuredKeys: form.requiredKeys
        .split(",")
        .map((k) => k.trim())
        .filter(Boolean),
      optionalStructuredKeys: [],
      fallbackTextTemplate: form.fallbackText || "Information not available.",
      missingDataBehavior: form.missingDataBehavior,
    },
    safetyRules: {
      preventHallucination: form.preventHallucination,
      blockFinancialGuessing: form.blockFinancial,
      blockMedicalDiagnosis: false,
      blockLegalClaims: false,
      requireSourceGrounding: form.requireGrounding,
    },
    ragOptions: {
      enabled: form.ragEnabled,
      maxSnippets: 5,
      includeSourceName: true,
      includeConfidenceScore: true,
    },
  };
}

